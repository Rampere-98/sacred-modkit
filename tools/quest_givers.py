#!/usr/bin/env python
"""Builds src/game/quest_givers.inc from the game's own scripts (Manolito's blocks BN and BR):
docs/Sacred/Misiones-dadores.tsv (the quests with a script variable) and docs/Sacred/Misiones-dadores-dq.tsv (the DQ_
quests 10250-10261 and 15001-15084, given by an NPC that QIS_OnSetUp<n> sets up; they have no variable).

Usage: python -I tools/quest_givers.py <sacred-bild docs dir>
Every «dador» row of the main TSV; of the DQ_ ones, one a quest: the one at «pos_Auftraggeber_<n>» / «dlg_<n>_start». 10254 is left
out (the journal's 210, the same quest).
"""
import os, sys

docs = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
out_path = os.path.join(here, "..", "src", "game", "quest_givers.inc")


def rows(name):
    lines = open(os.path.join(docs, "Sacred", name), encoding="utf8").read().splitlines()
    head = lines[0].split("\t")
    return [dict(zip(head, l.split("\t"))) for l in lines[1:] if l.strip()]


givers = {}    # number -> rows (a quest of the main TSV may have two givers: 503)
for r in rows("Misiones-dadores.tsv"):
    if r["papel"] == "dador":
        givers.setdefault(int(r["mision"]), []).append(r)
dq = {}
for r in rows("Misiones-dadores-dq.tsv"):
    n = int(r["mision"])
    if r["papel"] != "dador" or not (10250 <= n <= 10261 or 15001 <= n <= 15084) or n == 10254:
        continue
    main = "Auftraggeber" in r.get("posicion_con_nombre", "") or r.get("dialogo", "").endswith("_start")
    if n not in dq or (main and not dq[n][1]):
        dq[n] = (r, main)
for n, (r, _) in dq.items():
    givers.setdefault(n, [r])
with open(out_path, "w", encoding="utf8", newline="\n") as f:
    f.write("// Quest givers from the game's own scripts (Manolito's blocks BN and BR, docs/Sacred/Misiones-dadores.tsv and\n"
            "// Misiones-dadores-dq.tsv, 2026-11-16/17): {quest number, tile x, tile y, sector's lowest level, highest level};\n"
            "// generated by tools/quest_givers.py, one line a giver. The DQ_ quests (10250+) have no script variable.\n")
    for n in sorted(givers):
      for r in givers[n]:
        f.write(f'{{{n}, {r["casilla_x"]}, {r["casilla_y"]}, {r["nivel_min"]}, {r["nivel_max"]}}},\n')
print(f"{len(givers)} givers ({len(dq)} DQ) written to {os.path.normpath(out_path)}")
